"""Read the Ubisoft Connect library cache used by Playnite.

Ubisoft's account website is not the library source. Playnite reads the local
``cache/configuration/configurations`` protobuf generated by Ubisoft Connect,
then resolves the embedded product YAML and its localized artwork names.
"""

import os
from pathlib import Path

import yaml


UBISOFT_CONFIGURATIONS_PATH = Path(
    os.environ.get("UBISOFT_CONFIGURATIONS_PATH")
    or Path.home()
    / "AppData"
    / "Local"
    / "Ubisoft Game Launcher"
    / "cache"
    / "configuration"
    / "configurations"
)
ASSET_BASE_URL = "https://ubistatic3-a.akamaihd.net/orbit/uplay_launcher_3_0/assets/"


def _read_varint(data, offset):
    value = 0
    shift = 0
    while offset < len(data):
        byte = data[offset]
        offset += 1
        value |= (byte & 0x7F) << shift
        if byte < 0x80:
            return value, offset
        shift += 7
        if shift >= 64:
            break
    raise ValueError("Invalid Ubisoft cache protobuf varint")


def _fields(data):
    """Yield ``(field_number, wire_type, value)`` from a protobuf message."""
    offset = 0
    while offset < len(data):
        key, offset = _read_varint(data, offset)
        field_number = key >> 3
        wire_type = key & 0x07
        if not field_number:
            raise ValueError("Invalid Ubisoft cache protobuf field number")

        if wire_type == 0:
            value, offset = _read_varint(data, offset)
        elif wire_type == 1:
            end = offset + 8
            if end > len(data):
                raise ValueError("Truncated Ubisoft cache protobuf field")
            value = data[offset:end]
            offset = end
        elif wire_type == 2:
            length, offset = _read_varint(data, offset)
            end = offset + length
            if end > len(data):
                raise ValueError("Truncated Ubisoft cache protobuf field")
            value = data[offset:end]
            offset = end
        elif wire_type == 5:
            end = offset + 4
            if end > len(data):
                raise ValueError("Truncated Ubisoft cache protobuf field")
            value = data[offset:end]
            offset = end
        else:
            raise ValueError(f"Unsupported Ubisoft cache protobuf wire type {wire_type}")

        yield field_number, wire_type, value


def _parse_cache(data):
    games = []
    for field_number, wire_type, value in _fields(data):
        if field_number != 1 or wire_type != 2:
            continue

        game = {}
        for game_field, game_wire_type, game_value in _fields(value):
            if game_field in (1, 2) and game_wire_type == 0:
                game[game_field] = game_value
            elif game_field == 3 and game_wire_type == 2:
                game[game_field] = game_value.decode("utf-8")
        if game.get(1) is not None and game.get(3):
            games.append(game)
    return games


def _localized_asset(root, localizations, field_name):
    value = root.get(field_name)
    if not value:
        return None
    value = localizations.get(value, value)
    return f"{ASSET_BASE_URL}{value}"


def _product_games(cache_games):
    products = []
    for cache_game in cache_games:
        product = yaml.safe_load(cache_game[3])
        if isinstance(product, dict) and isinstance(product.get("root"), dict):
            products.append((cache_game, product))

    dlc_ids = {
        addon.get("id")
        for _, product in products
        for addon in (product["root"].get("addons") or [])
        if isinstance(addon, dict) and addon.get("id") is not None
    }

    games = []
    seen_ids = set()
    for cache_game, product in products:
        root = product["root"]
        uplay_id = cache_game[1]
        if (
            root.get("third_party_platform") is not None
            or root.get("is_ulc", False)
            or uplay_id in dlc_ids
            or root.get("start_game") is None
            or not root.get("name")
            or uplay_id in seen_ids
        ):
            continue

        localization_data = product.get("localizations") or {}
        localizations = localization_data.get("default") or {}
        if not isinstance(localizations, dict):
            localizations = {}
        name = localizations.get(root["name"], root["name"])
        if not name:
            continue

        seen_ids.add(uplay_id)
        games.append({
            "store_id": str(uplay_id),
            "name": name,
            "cover_image": _localized_asset(root, localizations, "thumb_image"),
            "background_image": _localized_asset(root, localizations, "background_image"),
            "icon": _localized_asset(root, localizations, "icon_image"),
            "supported_platforms": ["pc_windows"],
        })
    return games


def get_ubisoft_library(path=None):
    """Return games from Ubisoft Connect's Playnite-compatible local cache."""
    cache_path = Path(path or UBISOFT_CONFIGURATIONS_PATH)
    if not cache_path.is_file():
        print(f"  Ubisoft Connect cache not found: {cache_path}")
        return None

    try:
        cache_games = _parse_cache(cache_path.read_bytes())
        games = _product_games(cache_games)
    except (OSError, UnicodeDecodeError, ValueError, yaml.YAMLError) as exc:
        print(f"  Ubisoft cache error: {exc}")
        return None

    print(f"  Found {len(games)} Ubisoft Connect games")
    return games
